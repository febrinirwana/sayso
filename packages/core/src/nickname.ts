export function nicknameOf(address: string): string {
  if (!/^0x[0-9a-f]{40}$/i.test(address)) {
    throw new Error("Invalid 20-byte hex address");
  }
  const hash = keccak256(hexToBytes(address.toLowerCase() as Hex));
  const adjectiveIndex = Number.parseInt(hash.slice(2, 4), 16) % 128;
  const nounIndex = Number.parseInt(hash.slice(4, 6), 16) % 128;
  return `${ADJECTIVES[adjectiveIndex]} ${NOUNS[nounIndex]}`;
}
